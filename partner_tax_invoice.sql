--   · 판매처(세금계산서를 받는 법인명) → 거래처명과 다른 경우가 있습니다
--     예) 거래처 "헤이딜러" 의 계산서는 "주식회사 피알앤디테크베이" 앞으로 나갑니다
--
-- 사내 공유 폴더의 지난 요청서 20장에서 긁어온 값을 그대로 넣습니다.

-- 0) 중복 거래처 정리
--    "YF" 는 "YF 인터네셔널" 의 잘린 이름이고, "트리플헛츠" 는 "트리플렛츠" 의 오타입니다.
--    둘 다 견적서·거래 건·수금 내역이 하나도 걸려 있지 않은 것을 확인하고 지웁니다.
--    혹시라도 그 사이에 뭔가 연결됐다면 아래 조건에 걸려 지워지지 않습니다.
delete from partners p
where p.name in ('YF', '트리플헛츠')
  and not exists (select 1 from partner_quotes   q where q.partner_id = p.id)
  and not exists (select 1 from partner_deals    d where d.partner_id = p.id)
  and not exists (select 1 from partner_payments y where y.partner_id = p.id);

-- 1) 거래처에 칸을 추가합니다.
