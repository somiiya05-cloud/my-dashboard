  created_at timestamptz not null default now()
);

alter table tax_invoice_recipients enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'tax_invoice_recipients' and policyname = 'public read access') then
    create policy "public read access" on tax_invoice_recipients for select using (true);
    create policy "public insert access" on tax_invoice_recipients for insert with check (true);
    create policy "public update access" on tax_invoice_recipients for update using (true);
    create policy "public delete access" on tax_invoice_recipients for delete using (true);
  end if;
end $$;

