create table if not exists mall_products (
  id bigint generated by default as identity primary key,
  brand text not null,
  product_no text not null,
  product_name text,
  price integer,
  shipping_fee integer,          -- null = 상세페이지에서 배송비를 못 찾음
  image_url text,
  product_url text,
  is_hidden boolean not null default false,   -- 사이트맵에 없는 히든링크
  checked_at timestamptz not null default now(),
  unique (brand, product_no)
);

create index if not exists mall_products_brand_idx on mall_products (brand);

alter table mall_products enable row level security;
drop policy if exists "public read access"   on mall_products;
drop policy if exists "public insert access" on mall_products;
drop policy if exists "public update access" on mall_products;
drop policy if exists "public delete access" on mall_products;
create policy "public read access"   on mall_products for select using (true);
create policy "public insert access" on mall_products for insert with check (true);
create policy "public update access" on mall_products for update using (true);
create policy "public delete access" on mall_products for delete using (true);

-- 크롬 북마크 "자사몰" 폴더에 있는데 검수 목록에 빠져 있던 두 곳 (둘 다 카페24)
insert into mall_sites (brand, url, platform, sort_order) values
  ('폴크',       'https://porke.co.kr',    'cafe24', 10),
  ('슬로우케어', 'https://slowcare.co.kr', 'cafe24', 11)
on conflict (brand) do update
  set url = excluded.url, platform = excluded.platform, sort_order = excluded.sort_order;

-- 확인 — mall_products 가 0으로 나오고, 자사몰이 11곳이면 성공입니다.
select (select count(*) from mall_products) as "mall_products 행 수",
       (select count(*) from mall_sites where is_active) as "검수 대상 자사몰";
