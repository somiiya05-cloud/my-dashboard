-- 공구 가격표 — 유관부서 "옵션 제안" 표
-- Supabase 프로젝트 대시보드 > SQL Editor 에 전체를 붙여넣고 Run 하세요. 여러 번 실행해도 안전합니다.
--
-- 유관부서가 만들고 싶은 공구 옵션(구성·희망 공구가·수수료율)을 남기면, 영업팀 화면의
-- "공구 가격표" 메뉴에 알림 숫자가 뜨고, 영업팀이 원가·물류비를 넣어 손익을 짠 뒤 가격표에 올립니다.
--
--   · status        : 대기 → 완료(가격표에 올림) / 반려
--   · price_item_id : 완료되면 만들어진 가격표 옵션(groupbuy_price_items.id) 하나
--   · reply         : 영업팀이 남기는 답(반려 사유 등)

create table if not exists groupbuy_option_proposals (
  id bigint generated by default as identity primary key,
  proposer text,
  brand text not null,
  product text not null,
  spec text not null,
  desired_price numeric,
  fee_rate numeric,
  memo text,
  status text not null default '대기',
  reply text,
  price_item_id bigint,
  created_at timestamptz not null default now(),
  handled_at timestamptz
);

create index if not exists groupbuy_option_proposals_status_idx on groupbuy_option_proposals (status, created_at);

alter table groupbuy_option_proposals enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'groupbuy_option_proposals' and policyname = 'public read access') then
    create policy "public read access" on groupbuy_option_proposals for select using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'groupbuy_option_proposals' and policyname = 'public insert access') then
    create policy "public insert access" on groupbuy_option_proposals for insert with check (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'groupbuy_option_proposals' and policyname = 'public update access') then
    create policy "public update access" on groupbuy_option_proposals for update using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'groupbuy_option_proposals' and policyname = 'public delete access') then
    create policy "public delete access" on groupbuy_option_proposals for delete using (true);
  end if;
end $$;

-- 제안이 들어오면 열려 있는 영업팀 화면에 바로 알림이 가도록 실시간 발행에 넣습니다.
do $$
begin
  begin
    alter publication supabase_realtime add table groupbuy_option_proposals;
  exception when duplicate_object then
    raise notice 'groupbuy_option_proposals 는 이미 실시간 발행에 등록돼 있습니다.';
  end;
end $$;

-- 확인 — "만들어진 표 1 / 실시간 1" 이 나오면 성공입니다.
select
  (select count(*) from information_schema.tables where table_schema = 'public' and table_name = 'groupbuy_option_proposals') as "만들어진 표",
  (select count(*) from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'groupbuy_option_proposals') as "실시간";
