-- CX팀 리뷰작업 트래킹 표입니다. (사이드바 CS > 리뷰작업)
-- Supabase 프로젝트 대시보드 > SQL Editor 에 전체를 붙여넣고 Run 하세요.
--
-- 한 줄 = CX팀에 요청한 리뷰작업 1건
--   · requested_at : 요청일
--   · purchase_date: 구매(예정)일
--   · review_count : 리뷰 건수
--   · upload_date  : 리뷰 적재(예정)일
--   · status       : 요청 → 구매완료 → 적재완료 (또는 취소)

create table if not exists review_tasks (
  id bigint generated by default as identity primary key,
  product_name text not null,
  channel text,
  requester text,
  requested_at date not null default current_date,
  purchase_date date,
  review_count integer,
  upload_date date,
  status text not null default '요청',
  memo text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists review_tasks_requested_idx on review_tasks (requested_at desc);

alter table review_tasks enable row level security;

drop policy if exists "public read access" on review_tasks;
drop policy if exists "public insert access" on review_tasks;
drop policy if exists "public update access" on review_tasks;
drop policy if exists "public delete access" on review_tasks;

create policy "public read access" on review_tasks for select using (true);
create policy "public insert access" on review_tasks for insert with check (true);
create policy "public update access" on review_tasks for update using (true);
create policy "public delete access" on review_tasks for delete using (true);

-- 확인 — 아래 결과가 1줄 나오면 성공입니다.
select table_name as "만들어진 표"
from information_schema.tables
where table_schema = 'public' and table_name = 'review_tasks';
