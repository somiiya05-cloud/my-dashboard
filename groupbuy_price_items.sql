-- 손익은 저장하지 않고 화면이 매번 계산합니다(엑셀 "금액최종" 시트와 같은 식).
--   수수료 = 공구판매가 × 수수료율
--   부가세 = 공구판매가 ÷ 11
--   경비   = 공구판매가 × 경비율(기본 24%)
--   손익   = 공구판매가 − 수수료 − 원가 − 물류비 − 부가세 − 경비
--   손익률 = 손익 ÷ 공구판매가
--
--   · product      : 옵션을 묶는 상품명(화면에서 한 덩어리로 보입니다)
--   · units        : 구성 개수(1+1 → 2). 객단가 = 공구판매가 ÷ units
--   · mall_price   : 자사몰가(할인율 기준), ss/coupang/hidden_price 는 참고용 비교가
--   · cost         : 이 옵션 전체 원가(구성 개수만큼 곱한 값)

