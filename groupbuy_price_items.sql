  option_name text not null,
  sort_order int not null default 0,
  units numeric not null default 1,
  mall_price numeric,
  ss_price numeric,
  coupang_price numeric,
  hidden_price numeric,
  gb_price numeric,
  fee_rate numeric,
  cost numeric,
  logistics numeric,
  expense_rate numeric not null default 0.24,
  memo text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists groupbuy_price_items_brand_idx on groupbuy_price_items (brand, product, sort_order);

