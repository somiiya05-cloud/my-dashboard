-- 외부몰 판매가 변동 기록 — 「외부몰 판매가」 화면의 가격 추이에 씁니다.
-- Supabase 프로젝트 대시보드 > SQL Editor 에 전체를 붙여넣고 Run 하세요.
-- 여러 번 실행해도 안전합니다.
--
-- 왜 필요한가:
--   mall_product_prices 는 품번 × 몰마다 한 줄만 두고, 가격을 다시 읽어올 때마다
--   그 줄을 덮어씁니다. 그래서 "지난주에 얼마였는지"가 어디에도 남지 않습니다.
--   아래 트리거가 가격이 바뀔 때마다 한 줄씩 여기에 남깁니다.
--
-- 누가 넣나:
--   아무도 따로 넣지 않습니다. mall_product_prices 에 값이 들어오거나 바뀌면
--   DB가 알아서 남깁니다. 가격을 읽어오는 쪽(수집기·엑셀 업로드·손으로 고치기)이
--   무엇이든 똑같이 남으므로, 수집하는 코드는 건드릴 필요가 없습니다.
--
-- 값이 그대로면 남기지 않습니다. 같은 가격을 열 번 읽어도 줄은 늘지 않고,
-- 가격이 실제로 달라진 날만 한 줄씩 쌓입니다.

-- ── 1. 표 ────────────────────────────────────────────────────────────────
create table if not exists mall_price_history (
  id bigint generated by default as identity primary key,
  product_code text not null,
  mall text not null,
  brand text,
  product_name text,
  price numeric,                 -- 그때 몰에서 팔리던 가격(할인 적용가)
  list_price numeric,            -- 그때 몰에 표시된 정가
  memo text,
  checked_at timestamptz not null,   -- 그 가격을 읽어온 시각 (mall_product_prices 와 같은 값)
  recorded_at timestamptz not null default now()
);

create index if not exists mall_price_history_key_idx
  on mall_price_history (product_code, mall, checked_at);
create index if not exists mall_price_history_at_idx
  on mall_price_history (checked_at desc);

-- 같은 품번·몰·시각이 두 번 들어가지 않게 합니다(같은 수집을 두 번 돌려도 안전).
create unique index if not exists mall_price_history_uniq
  on mall_price_history (product_code, mall, checked_at);

-- 읽기와 쌓기만 열어 둡니다. 브라우저에서는 지울 수 없어, 한 번 남은 기록이
-- 실수로 사라지지 않습니다. 잘못 들어간 줄은 SQL Editor 에서 지우면 됩니다:
--   delete from mall_price_history where product_code = '품번';
alter table mall_price_history enable row level security;
drop policy if exists "public read access"   on mall_price_history;
drop policy if exists "public insert access" on mall_price_history;
create policy "public read access"   on mall_price_history for select using (true);
create policy "public insert access" on mall_price_history for insert with check (true);


-- ── 2. 가격이 바뀌면 자동으로 남기기 ──────────────────────────────────────
create or replace function mall_price_history_log() returns trigger
language plpgsql security definer as $$
begin
  -- 품번이 없는 줄(옛 자료)은 어느 상품인지 가릴 수 없어 남기지 않습니다.
  if new.product_code is null then return new; end if;

  -- 고칠 때는 가격이 실제로 달라진 경우만 남깁니다.
  if tg_op = 'UPDATE'
     and new.price is not distinct from old.price
     and new.list_price is not distinct from old.list_price then
    return new;
  end if;

  insert into mall_price_history
    (product_code, mall, brand, product_name, price, list_price, memo, checked_at)
  values
    (new.product_code, new.mall, new.brand, new.product_name,
     new.price, new.list_price, new.memo, coalesce(new.checked_at, now()))
  on conflict (product_code, mall, checked_at) do nothing;

  return new;
end $$;

drop trigger if exists mall_price_history_trg on mall_product_prices;
create trigger mall_price_history_trg
  after insert or update on mall_product_prices
  for each row execute function mall_price_history_log();


-- ── 3. 지금 값을 첫 점으로 넣어 둡니다 ────────────────────────────────────
-- 지난 가격은 어디에도 남아 있지 않아 되살릴 수 없습니다.
-- 지금 들어와 있는 값이 추이의 시작점이 되고, 다음 수집부터 선이 이어집니다.
insert into mall_price_history
  (product_code, mall, brand, product_name, price, list_price, memo, checked_at)
select product_code, mall, brand, product_name, price, list_price, memo, coalesce(checked_at, now())
from mall_product_prices
where product_code is not null
on conflict (product_code, mall, checked_at) do nothing;

-- API 가 새 표를 바로 알아보게 표 목록을 다시 읽힙니다.
notify pgrst, 'reload schema';

-- ── 확인 ─────────────────────────────────────────────────────────────────
select
  (select count(*) from mall_product_prices where product_code is not null) as "지금 가격 줄",
  (select count(*) from mall_price_history)                                as "기록된 줄",
  (select count(distinct product_code || '|' || mall) from mall_price_history) as "품번·몰 수";
